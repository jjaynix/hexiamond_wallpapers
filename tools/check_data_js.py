import json
import math
import sys
from src.verify import _canon
from src.wallpaper import D6, classify_group, hnf, lattice_index, lattice_invariant, lattice_reduce, mat_vec, S_of_triangle
S3 = math.sqrt(3) / 2

def _inside(poly, x, y):
    c, n = (False, len(poly))
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c

def _tile_triangles(poly, center, m):
    pts = [((p[0] + center[0]) * m, (p[1] + center[1]) * m) for p in poly]
    xs, ys = ([p[0] for p in pts], [p[1] for p in pts])
    out = []
    for r in range(int(min(ys) / S3) - 2, int(max(ys) / S3) + 3):
        for q in range(int(min(xs) - r / 2) - 4, int(max(xs) - r / 2) + 5):
            for o in (0, 1):
                a = (q + (1 + o) / 3, r + (1 + o) / 3)
                if _inside(pts, a[0] + a[1] / 2, a[1] * S3):
                    out.append((q, r, o))
    return out

def _int_vec(t, m):
    r = t[1] * m / S3
    q = t[0] * m - r / 2
    if abs(q - round(q)) > 1e-06 or abs(r - round(r)) > 1e-06:
        raise ValueError('lattice vector is not on the grid')
    return (round(q), round(r))

def check_row(g):
    m = g.get('refine', 1)
    L = hnf([_int_vec(g['t1'], m), _int_vec(g['t2'], m)])
    tiles = [_tile_triangles(im['polygon'], g['center'], m) for im in g['images']]
    if any((len(t) != 6 * m * m for t in tiles)):
        return {'ok': False, 'why': f'tile sizes {[len(t) for t in tiles]}'}
    seen = set()
    for t in tiles:
        for q, r, o in t:
            cls = (lattice_reduce(L, (q, r)), o)
            if cls in seen:
                return {'ok': False, 'why': 'tiles overlap'}
            seen.add(cls)
    if len(seen) != 2 * lattice_index(L):
        return {'ok': False, 'why': 'gaps'}
    if g.get('generated'):
        from src.verify import verify_generated
        rep = {'lattice': L, 'tiles': tiles, 'tiles_per_cell': len(tiles), 'elements': g['elements'], 'group': g['group'], 'mirror': g['mirror'], 'glide': g['glide'], 'rotation_order': g['order']}
        try:
            verify_generated(rep, None, m)
        except AssertionError as e:
            return {'ok': False, 'why': str(e)}
        return {'ok': True, 'group': g['group'], 'tiles_per_cell': len(tiles), 'generated': True}
    reps = {_canon(L, [S_of_triangle(*x) for x in t]): None for t in tiles}
    a, c = (L[0][0], L[1][1])
    trans = [(tq, tr) for tr in range(c) for tq in range(a) if all((_canon(L, [(x + 3 * tq, y + 3 * tr) for x, y in S]) in reps for S in reps))]
    L2 = hnf([L[0], L[1]] + [v for v in trans if v != (0, 0)]) if len(trans) > 1 else L
    reps2 = {_canon(L2, list(S)): None for S in reps}
    a2, c2 = (L2[0][0], L2[1][1])
    el = {}
    for mi, M in enumerate(D6):
        if not lattice_invariant(L2, M):
            continue
        for tr in range(c2):
            for tq in range(a2):
                if all((_canon(L2, [(mat_vec(M, s)[0] + 3 * tq, mat_vec(M, s)[1] + 3 * tr) for s in S]) in reps2 for S in reps2)):
                    el[mi] = (tq, tr)
                    break
            if mi in el:
                break
    info = classify_group(L2, el)
    return {'ok': True, 'group': info['name'], 'tiles_per_cell': len(reps2)}

def main(path):
    s = open(path).read()
    data = json.loads(s[s.index('{'):].rstrip().rstrip(';'))
    bad = 0
    for h in data['hexiamonds']:
        for g in h['groups']:
            r = check_row(g)
            good = r['ok'] and r['group'] == g['group']
            bad += not good
            detail = (f"generated by {r['group']} (transitive, verified), {r['tiles_per_cell']} tiles/cell" if r.get('generated') else f"true group {r['group']}, {r['tiles_per_cell']} tiles/cell") if r['ok'] else f"INVALID: {r['why']}"
            print(f"{('OK ' if good else 'BAD')} {h['name']:18} claims {g['group']:5} -> {detail}")
    print(f'\n{bad} row(s) differ from their claim')
    return bad
if __name__ == '__main__':
    sys.exit(1 if main(sys.argv[1]) else 0)
